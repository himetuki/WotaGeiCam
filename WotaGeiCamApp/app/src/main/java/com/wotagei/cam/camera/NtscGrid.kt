package com.wotagei.cam.camera

/**
 * NTSC 制式的**非整数帧率档**网格步长（纯函数，无 Android 依赖，可在 JVM 直接单测）。
 *
 * # 为什么要有这个表（不是把 fps 升成 Double）
 * 29.97/23.976/59.94 这三档是 30000/1001、24000/1001、60000/1001——`1e9/fps` 取整后会得到
 * 一个**不等于真实周期**的步长（23.976 档：41708333ns vs 整数档的 41666666ns，差 0.1%）。
 * 差得不多，但它是**系统性**的：每一帧都差，683 帧就攒出 7ms，成片 `r_frame_rate` 与真值分家。
 *
 * # 为什么**不**把全链 fps 升 Double/String
 * 为 3 个档位把平台面（相机请求、参数总线、RecordProfile、UI 显示、播放器）全改成浮点，
 * 回归面远大于收益；浮点还会把 `24` 显示成 `24.0000001`。所以走 **Int fps + 映射表**：
 * 链上仍然是 Int（UI、请求、容器声明都不动），只有**网格步长**这一个算术点查表。
 *
 * # 精度
 * 步长取 `round(1e9 × 1001 / (1000 × fps))`：24→41708333ns、30→33366667ns、60→16683333ns。
 * 每帧累积误差 < 0.5ns，1000 帧 < 500ns，**永不产生空洞**（相邻戳差恒 ≥ 步长，不会有「跳格」）。
 *
 * # 不映射的档
 * - **25 / 50** 是 exact 档，`1e9/25`、`1e9/50` 本来就整除，没有近似可言，不进表；
 * - **120 / 240** 在本工程的可选档里不出现（超高帧走的是别的口径），也不进表；
 * - 其余一律返回 0，调用方**必须**在 0 时退回 `1e9/fps`（见 [GlRenderEngine.stampEncoderPresentation]），
 *   不许把 0 当步长传下去——那会让整段的戳全部并到同一枚。
 *
 * @param fps 名义档位（Int）
 * @return 该档的网格步长（ns）；**不在映射表里返回 0**，含义是「这一档不是 NTSC 非整数档」
 */
internal fun ntscGridStepNs(fps: Int): Long {
    // 分母写死 1000×fps：30000/29.97、24000/23.976、60000/59.94 的统一写法，无浮点
    val den = when (fps) {
        24 -> 24_000L
        30 -> 30_000L
        60 -> 60_000L
        else -> return 0L
    }
    // + den/2 是整数四舍五入（分子恒为正，等价于 round(分子/分母)）
    return (1_000_000_000L * 1001L + den / 2) / den
}
